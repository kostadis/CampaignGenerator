"""Put the re-run's gaps beside the 31 the GM accepted, and refuse to judge them.

What this does mechanically: counts, the dialogue/narration balance, and a
side-by-side listing of every accepted marker against every new one.

What it deliberately does NOT do: decide that a new gap "is" an accepted gap.
Boundaries shift and the prompts have no common structure, so matching them
means judging that two differently-worded sentences describe the same passage —
a scope-and-attribution decision, which is the GM's under Constitution II. A
similarity score presented as a verdict is exactly the Optimistic Lie this repo
keeps paying for.

The overlap figure below is therefore a **reading order**, not a match. It sorts
the new markers so that the one most likely to correspond appears first under
each accepted gap, so the GM reads pairs instead of scanning two lists. A high
overlap is not evidence of anything; a gap with no plausible partner is worth
looking at first, which is the whole point.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = ROOT.parents[1] / "specs/028-gap-marking-contract"
MARKER_RE = re.compile(r"\[GM NARRATION — TO BE WRITTEN:\s*(.*?)\]\s*$", re.S)

STOP = set("""a an and are as at be been but by for from had has have he her his in into is it
its of on or she that the their them there they this to was were which who with you your
just then than so had have""".split())


def body(marker: str) -> str:
    m = MARKER_RE.search(marker.strip())
    return (m.group(1) if m else marker).strip()


def terms(text: str) -> set[str]:
    return {w for w in re.findall(r"[A-Za-z']{3,}", text.lower()) if w not in STOP}


def overlap(a: str, b: str) -> float:
    ta, tb = terms(a), terms(b)
    return len(ta & tb) / len(ta | tb) if ta and tb else 0.0


def main() -> None:
    accepted = json.loads((SPEC / "accepted_gaps.json").read_text(encoding="utf-8"))
    out = ["# Re-confirmation — the accepted gaps against the ported prompt", ""]
    out += [
        "Generated by `compare.py`. The **overlap** column is a reading order, not a",
        "verdict: whether two differently-worded markers describe the same passage is a",
        "scope decision and stays the GM's. A `—` means nothing in the new render shares",
        "vocabulary with the accepted gap, which is the row to read first.",
        "",
    ]
    totals = {"accepted": 0, "new": 0}
    for arm in sorted(accepted["arms"]):
        run_path = ROOT / "per-scene" / arm / "run.json"
        if not run_path.is_file():
            out += [f"## {arm}", "", "_not rendered_", ""]
            continue
        run = json.loads(run_path.read_text(encoding="utf-8"))
        was = accepted["arms"][arm]["markers"]
        now = run.get("markers", [])
        totals["accepted"] += len(was)
        totals["new"] += len(now)
        out += [
            f"## {arm}", "",
            f"- accepted: **{len(was)}** · this run: **{len(now)}** "
            f"(delta {len(now) - len(was):+d})",
            f"- dialogue lines {run.get('dialogue_lines')} vs narration "
            f"{run.get('narration_lines')} "
            f"(ratio {run.get('dialogue_lines', 0) / max(1, run.get('narration_lines', 1)):.1f}×)",
            f"- {run.get('words')} words in {run.get('seconds')}s",
            "",
            "| # | Accepted gap | Closest new gap | Overlap |",
            "|---|---|---|---|",
        ]
        for i, acc in enumerate(was, 1):
            ranked = sorted(((overlap(body(acc), body(n)), n) for n in now),
                            key=lambda p: -p[0])
            score, best = ranked[0] if ranked else (0.0, "")
            shown = body(best)[:110] + "…" if score >= 0.08 else "—"
            out.append(f"| {i} | {body(acc)[:110]}… | {shown} | "
                       f"{score:.2f} |" if score >= 0.08 else
                       f"| {i} | {body(acc)[:110]}… | — | — |")
        out.append("")
        extra = [n for n in now
                 if max((overlap(body(a), body(n)) for a in was), default=0) < 0.08]
        if extra:
            out += ["**New gaps with no vocabulary in common with an accepted one** — "
                    "each needs a ruling, and one landing where the GM ruled the scope "
                    "wrong is the bigger signal:", ""]
            out += [f"- {body(n)}" for n in extra] + [""]

    out += ["## Totals", "",
            f"- accepted across four scenes: **{totals['accepted']}**",
            f"- this run: **{totals['new']}**", ""]

    bundle_path = ROOT / "bundle" / "run.json"
    if bundle_path.is_file():
        b = json.loads(bundle_path.read_text(encoding="utf-8"))
        out += [
            "## Bundle (SC-009)", "",
            f"One exchange, four scenes: **{b.get('marker_count')}** markers against "
            f"**{totals['new']}** from the same scenes rendered one call each.",
            "",
            "This is the evidence the Q2 ruling did not have. Gap marking was admitted to "
            "the all-scenes path on the strength of per-scene runs; a bundle marking "
            "materially fewer gaps than the per-scene run of the same scenes is a finding, "
            "not a rounding error, and refusing the combination stays available.",
            "",
        ]

    (ROOT / "FINDINGS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out[:40]))
    print(f"\n[wrote {ROOT / 'FINDINGS.md'}]")


if __name__ == "__main__":
    main()
